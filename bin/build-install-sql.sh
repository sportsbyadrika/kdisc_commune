#!/usr/bin/env bash
#
# Build deploy/sql/install.sql — the complete database for a FIRST install, importable with phpMyAdmin
# (shared hosting without SSH): every table (database/migrations, in order), the reference data from
# `db:seed` in production mode (centre, floors, seats, rates, facilities, settings — NO staff logins) and the
# `migrations` bookkeeping rows, so later deploys only run newer migrations.
#
# Run after adding a migration or changing a seeder, then commit deploy/sql/install.sql:
#     bin/build-install-sql.sh
# Needs a local MySQL/MariaDB where MYSQL (default: "mysql") can create databases.
# tests/Unit/InstallSqlTest fails while install.sql is missing a migration.

set -Eeuo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
ROOT="$PWD"
OUT="$ROOT/deploy/sql/install.sql"
MYSQL="${MYSQL:-mysql}"
DUMP="${MYSQLDUMP:-$(command -v mariadb-dump || command -v mysqldump)}"
DB="commune_installsql_$$"
USER_PW="installsql_$$"

cleanup() { $MYSQL -e "DROP DATABASE IF EXISTS \`$DB\`; DROP USER IF EXISTS '$DB'@'localhost';" >/dev/null 2>&1 || true; }
trap cleanup EXIT

echo "==> Building a scratch database $DB"
$MYSQL -e "CREATE DATABASE \`$DB\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
           CREATE USER '$DB'@'localhost' IDENTIFIED BY '$USER_PW';
           GRANT ALL ON \`$DB\`.* TO '$DB'@'localhost';"

# The app's own migrator + seeders, exactly as a production deploy runs them (APP_ENV=production: no demo staff).
export APP_ENV=production APP_DEBUG=false DB_HOST=localhost DB_DATABASE="$DB" DB_USERNAME="$DB" DB_PASSWORD="$USER_PW" \
       APP_KEY="base64:$(head -c 32 /dev/urandom | base64 | tr -d '\n')" LOG_PATH="/tmp/$DB.log"
php bin/console migrate >/dev/null
php bin/console db:seed >/dev/null

mkdir -p "$(dirname "$OUT")"
{
    cat <<EOF
-- ─────────────────────────────────────────────────────────────────────────────────────────────────────────────
-- Commune Workspace Management System — complete database for a FIRST install (phpMyAdmin / mysql import).
--
--   cPanel → phpMyAdmin → select the empty database (e.g. shooting_commune) → Import → this file → Go.
--
-- Creates every table, the Kottarakara reference data (centre, floors, seats, prices, facilities, settings) and
-- the migration records. No staff logins: create the first Centre Manager with bin/console user:create
-- (docs/DEPLOYMENT.md §13). Import into an EMPTY database only — never over a live one.
-- Generated by bin/build-install-sql.sh from $(git rev-parse --short HEAD 2>/dev/null || echo 'working tree') — do not edit by hand.
-- ─────────────────────────────────────────────────────────────────────────────────────────────────────────────

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';
SET time_zone = '+05:30';

-- ── Schema ────────────────────────────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS migrations (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    migration VARCHAR(255) NOT NULL,
    batch INT UNSIGNED NOT NULL,
    ran_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_migrations_migration (migration)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

EOF
    for f in database/migrations/*.sql; do
        printf '\n-- ── %s\n\n' "$(basename "$f")"
        cat "$f"
        printf '\n'
    done
    printf '\n-- ── Reference data (db:seed, production) ─────────────────────────────────────────────────────────────────────\n\n'
    "$DUMP" --no-create-info --replace --skip-triggers --complete-insert --skip-comments --skip-add-locks --skip-disable-keys \
        --no-tablespaces --skip-tz-utc --default-character-set=utf8mb4 \
        -h localhost -u "$DB" -p"$USER_PW" "$DB" \
        | grep -v '^/\*M!' | grep -v '^/\*!40' | grep -v '^$'
    printf '\nSET FOREIGN_KEY_CHECKS = 1;\n'
} > "$OUT"

echo "Done: $OUT ($(du -h "$OUT" | cut -f1), $(grep -c '^CREATE TABLE' "$OUT") tables, $(grep -c '^REPLACE INTO' "$OUT") data statements)"
